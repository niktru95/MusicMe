$files = Get-ChildItem -Path $root -Filter 't0*.js' | Sort-Object Name
foreach ($f in $files) {
  $name = $f.Name
  if (-not $sections.ContainsKey($name) -or $sections[$name].Count -eq 0) { continue }
  $text = [System.IO.File]::ReadAllText($f.FullName, [System.Text.Encoding]::UTF8)
  # Нужные секции уже добавлены? (по уникальной подстроке)
  $firstH = $sections[$name][0]
  $firstHShort = ($firstH -split "'")[0]
  if ($text.Contains($firstHShort)) {
    Write-Output ('SKIP ' + $name + ' already has section')
    continue
  }
  # Найти индекс закрывающего '],' перед блоком tasks. Возьмём последнее вхождение '  ],' после 'theory'
  $marker = "  ],`r`n  tasks:"
  if (-not $text.Contains($marker)) {
    $marker = "  ],`n  tasks:"
  }
  if (-not $text.Contains($marker)) {
    Write-Output ('MARKER-NOT-FOUND ' + $name)
    continue
  }
  $ins = $sections[$name] -join "`n"
  $newText = $text.Replace($marker, $ins + "`n" + $marker)
  [System.IO.File]::WriteAllText($f.FullName, $newText, $enc)
  Write-Output ('UPDATED ' + $name)
}